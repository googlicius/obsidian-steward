import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

const root = path.join(__dirname, '..');
const outFile = path.join(root, 'src/generated/modelsMetadata.ts');

const API_URL = 'https://models.dev/api.json';

const PROVIDER_ALLOWLIST = ['openai', 'anthropic', 'google', 'deepseek', 'xai'];

/**
 * @param {unknown} value
 * @returns {value is Record<string, unknown>}
 */
function isRecord(value) {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

/**
 * @param {unknown} value
 * @returns {string[]}
 */
function toStringArray(value) {
  if (!Array.isArray(value)) {
    return [];
  }

  const result = [];
  for (let i = 0; i < value.length; i++) {
    const item = value[i];
    if (typeof item === 'string') {
      result.push(item);
    }
  }
  return result;
}

/**
 * @param {unknown} model
 */
function stripModel(model) {
  if (!isRecord(model)) {
    return null;
  }

  const limit = isRecord(model.limit) ? model.limit : {};
  const modalities = isRecord(model.modalities) ? model.modalities : {};

  const context = typeof limit.context === 'number' ? limit.context : undefined;
  const output = typeof limit.output === 'number' ? limit.output : undefined;

  const entry = {
    toolCall: model.tool_call === true,
    temperature: model.temperature === true,
    reasoning: model.reasoning === true,
    input: toStringArray(modalities.input),
  };

  if (context !== undefined) {
    entry.context = context;
  }
  if (output !== undefined) {
    entry.output = output;
  }

  return entry;
}

const response = await fetch(API_URL);
if (!response.ok) {
  throw new Error(`Failed to fetch ${API_URL}: ${response.status} ${response.statusText}`);
}

const raw = await response.text();
let apiData;
try {
  apiData = JSON.parse(raw);
} catch (error) {
  throw new Error(`Failed to parse ${API_URL}: ${error instanceof Error ? error.message : error}`);
}

if (!isRecord(apiData)) {
  throw new Error(`Unexpected payload from ${API_URL}: expected object`);
}

const metadata = {};
let totalModels = 0;
let keptModels = 0;

for (let i = 0; i < PROVIDER_ALLOWLIST.length; i++) {
  const providerId = PROVIDER_ALLOWLIST[i];
  const provider = apiData[providerId];

  if (!isRecord(provider) || !isRecord(provider.models)) {
    console.log(`Skipped provider (not in API): ${providerId}`);
    continue;
  }

  const providerModels = {};
  const modelIds = Object.keys(provider.models);

  for (let j = 0; j < modelIds.length; j++) {
    const modelId = modelIds[j];
    totalModels += 1;

    const stripped = stripModel(provider.models[modelId]);
    if (!stripped) {
      continue;
    }

    providerModels[modelId] = stripped;
    keptModels += 1;
  }

  if (Object.keys(providerModels).length > 0) {
    metadata[providerId] = providerModels;
  }
}

const ts = `/* auto-generated by scripts/build-models-metadata.mjs — do not edit */

export interface BundledModelMetadata {
  /** limit.context (tokens) */
  context?: number;
  /** limit.output (tokens) */
  output?: number;
  toolCall: boolean;
  temperature: boolean;
  reasoning: boolean;
  /** modalities.input, e.g. ['text','image','pdf'] */
  input: string[];
}

/** provider id -> model id -> metadata */
export const MODELS_METADATA: Record<string, Record<string, BundledModelMetadata>> = ${JSON.stringify(metadata, null, 2)};
`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, ts);

console.log(
  `Wrote ${keptModels} models across ${Object.keys(metadata).length} providers (${keptModels}/${totalModels} from allowlisted providers present in API)`
);
