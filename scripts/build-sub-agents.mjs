import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import yaml from 'js-yaml';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

const root = path.join(__dirname, '..');
const sourceFile = path.join(root, 'agents/Sub Agents.md');
const outFile = path.join(root, 'src/generated/subAgents.ts');

function parseFrontmatter(raw) {
  const match = raw.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?/);

  if (!match) {
    throw new Error('agents/Sub Agents.md: missing YAML frontmatter');
  }

  const frontmatter = yaml.load(match[1]) ?? {};
  const body = raw.slice(match[0].length);

  return { frontmatter, body };
}

const raw = fs.readFileSync(sourceFile, 'utf8');
const { frontmatter, body } = parseFrontmatter(raw);
const version = Number.isFinite(frontmatter.version) ? frontmatter.version : 1;
const content = `---\nversion: ${version}\n---\n${body.replace(/^\n/, '')}`;

const ts = `/* auto-generated by scripts/build-sub-agents.mjs — do not edit */

export interface BundledSubAgents {
  version: number;
  content: string;
}

export const BUNDLED_SUB_AGENTS: BundledSubAgents = ${JSON.stringify({ version, content }, null, 2)};
`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, ts);

console.log(`Wrote bundled sub-agents v${version} to ${path.relative(root, outFile)}`);
