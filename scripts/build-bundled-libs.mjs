/**
 * Bundles heavy npm deps into IIFEs, LZ-compresses each, and emits
 * `src/generated/bundled*Payload.ts` for runtime eval (see `src/utils/bundledLibs.ts`).
 *
 * Multiple entries: each has its own `globalName` on `globalThis` after eval.
 */
import esbuild from 'esbuild';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import LZString from 'lz-string';
import { sharedExternal } from '../esbuild.shared.mjs';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const root = path.join(__dirname, '..');
const scriptFileName = path.basename(__filename);

function isTypeOnlySrcImport(importerPath, modulePath) {
  try {
    const src = fs.readFileSync(importerPath, 'utf8');

    const importStmtRe = /import[\s\S]*?\sfrom\s+['"]([^'"]+)['"]\s*;?/g;
    let m = null;
    while ((m = importStmtRe.exec(src))) {
      const spec = m[1];
      if (spec !== modulePath) {
        continue;
      }

      const stmt = m[0].trim();

      if (stmt.startsWith('import type ')) {
        return true;
      }

      const named = stmt.match(/^import\s*\{([\s\S]*?)\}\s*from\s*['"]/);
      if (named) {
        const inside = named[1];
        const parts = inside
          .split(',')
          .map(p => p.trim())
          .filter(Boolean);
        if (parts.length === 0) {
          return false;
        }
        for (const p of parts) {
          if (!p.startsWith('type ')) {
            return false;
          }
        }
        return true;
      }

      return false;
    }
  } catch {
    return false;
  }

  return false;
}

function noSrcRuntimeImportsForInternalsPlugin() {
  return {
    name: 'no-src-runtime-imports-for-internals',
    setup(build) {
      build.onResolve({ filter: /^src\// }, args => {
        if (!args.importer || !args.importer.includes(`${path.sep}internal${path.sep}`)) {
          return null;
        }

        if (isTypeOnlySrcImport(args.importer, args.path)) {
          return { path: args.path, external: true };
        }

        return {
          errors: [
            {
              text:
                `Forbidden runtime import "${args.path}" from "${args.importer}". ` +
                `The bundled-internals build must not import from "src/*" (except type-only imports).`,
            },
          ],
        };
      });
    },
  };
}

function getBundleConfig({ entryPoints, globalName, outFile, exportConst }) {
  return {
    entryPoints,
    bundle: true,
    platform: 'browser',
    format: 'iife',
    globalName,
    target: 'es2018',
    minify: true,
    write: false,
    external: sharedExternal,
    plugins:
      entryPoints.includes('internal/bundled-internals-entry.ts')
        ? [noSrcRuntimeImportsForInternalsPlugin()]
        : [],
    define: {
      'process.env.NODE_ENV': '"production"',
    },
    loader: { '.md': 'text', '.svg': 'text' },
    logLevel: 'info',
    exportConst,
    outFile,
  };
}

const bundles = [
  getBundleConfig({
    entryPoints: ['src/bundled-libs-entry.ts'],
    globalName: '__stewardBundledLibs',
    exportConst: 'BUNDLED_LIBS_LZ_B64',
    outFile: 'bundledLibsPayload.ts',
  }),
  getBundleConfig({
    entryPoints: ['src/bundled-libs-sync-entry.ts'],
    globalName: '__stewardBundledSyncLibs',
    exportConst: 'BUNDLED_SYNC_LIBS_LZ_B64',
    outFile: 'bundledSyncLibsPayload.ts',
  }),
  getBundleConfig({
    entryPoints: ['src/bundled-libs-desktop-entry.ts'],
    globalName: '__stewardBundledDesktopLibs',
    exportConst: 'BUNDLED_DESKTOP_LIBS_LZ_B64',
    outFile: 'bundledDesktopLibsPayload.ts',
  }),
  getBundleConfig({
    entryPoints: ['internal/bundled-internals-entry.ts'],
    globalName: '__stewardBundledInternals',
    exportConst: 'BUNDLED_INTERNALS_LZ_B64',
    outFile: 'bundledInternalsPayload.ts',
  }),
];

const outDir = path.join(root, 'src/generated');
fs.mkdirSync(outDir, { recursive: true });

for (const bundle of bundles) {
  const { exportConst, outFile, ...esbuildOptions } = bundle;
  const result = await esbuild.build(esbuildOptions);
  const js = result.outputFiles[0].text;
  const b64 = LZString.compressToBase64(js);
  const outPath = path.join(outDir, outFile);
  fs.writeFileSync(
    outPath,
    `// AUTO-GENERATED by ${scriptFileName} — do not edit manually\n` +
      `export const ${exportConst} = ${JSON.stringify(b64)};\n`,
    'utf8'
  );
  console.log(
    `Wrote ${path.relative(root, outPath)} (base64 length ${b64.length}, minified JS ${js.length} bytes)`
  );
}
